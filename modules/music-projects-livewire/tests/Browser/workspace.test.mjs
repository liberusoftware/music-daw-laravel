import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import test from 'node:test';
import { chromium } from 'playwright';

test('authenticated session editing, recovery and offline draft download/reconnect work in Chromium', async () => {
    const base = process.env.MUSIC_BROWSER_URL;
    const email = process.env.MUSIC_BROWSER_EMAIL;
    const password = process.env.MUSIC_BROWSER_PASSWORD;
    assert.ok(base && email && password, 'Configure a disposable host using MUSIC_BROWSER_URL, MUSIC_BROWSER_EMAIL and MUSIC_BROWSER_PASSWORD.');
    const workspace = process.env.MUSIC_BROWSER_WORKSPACE ?? '1';
    const workspacePath = process.env.MUSIC_BROWSER_PATH || `/music/workspaces/${encodeURIComponent(workspace)}/sessions`;
    const output = process.env.MUSIC_BROWSER_OUTPUT ?? 'browser-artifacts';
    await mkdir(output, { recursive: true });
    const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
    let page;
    const errors = [];
    try {
        const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1280, height: 960 } });
        page = await context.newPage();
        page.on('pageerror', error => errors.push(error.message));
        page.on('dialog', dialog => dialog.accept());
        await page.goto(`${base}/login`);
        await page.locator('input[name="email"]').fill(email);
        await page.locator('input[name="password"]').fill(password);
        await page.locator('button[type="submit"]').click();
        await page.waitForURL(url => !url.pathname.endsWith('/login'));
        const response = await page.goto(`${base}${workspacePath}`);
        assert.equal(response.status(), 200);
        assert.ok(response.headers()['cache-control'].includes('no-store'));
        await page.getByRole('heading', { name: 'Session draft', exact: true }).waitFor();
        await page.getByLabel('Session name', { exact: true }).fill('Browser session');
        await page.getByLabel('Name', { exact: true }).fill('Keys');
        await page.getByLabel('Kind', { exact: true }).selectOption('folder');
        await page.getByRole('button', { name: 'Add to draft', exact: true }).click();
        await page.getByLabel('Track 1', { exact: true }).waitFor();
        const folder = await page.locator('#parent-track option').filter({ hasText: 'Keys' }).getAttribute('value');
        await page.getByLabel('Name', { exact: true }).fill('Piano');
        await page.getByLabel('Kind', { exact: true }).selectOption('midi');
        await page.locator('#parent-track').selectOption(folder);
        await page.getByRole('button', { name: 'Add to draft', exact: true }).click();
        await page.getByLabel('Track 2', { exact: true }).waitFor();
        await page.getByLabel('Name', { exact: true }).fill('Unused');
        await page.getByLabel('Kind', { exact: true }).selectOption('audio');
        await page.getByRole('button', { name: 'Add to draft', exact: true }).click();
        await page.getByLabel('Track 3', { exact: true }).waitFor();
        await page.getByRole('button', { name: 'Remove Unused', exact: true }).click();
        await page.getByLabel('Track 3', { exact: true }).waitFor({ state: 'detached' });
        await page.locator('#folder-1').selectOption('');
        await page.getByText('Track move staged in this draft.', { exact: false }).waitFor();
        await page.locator('#folder-1').selectOption(folder);
        await page.waitForFunction(value => document.querySelector('#folder-1')?.value === value, folder);
        await page.getByRole('button', { name: 'Save checkpoint', exact: true }).click();
        await page.getByText('Checkpoint confirmed by the server.', { exact: true }).waitFor();
        await page.getByText(/Based on revision 1/).waitFor();
        const manifestDownload = page.waitForEvent('download');
        await page.getByRole('button', { name: 'Export saved revision', exact: true }).click();
        const manifestFile = path.join(output, 'session.music.json');
        await (await manifestDownload).saveAs(manifestFile);
        const manifest = JSON.parse(await readFile(manifestFile, 'utf8'));
        assert.equal(manifest.format, 'liberu.music.session');
        assert.equal(manifest.document.tracks.length, 2);
        assert.equal(manifest.document.tracks[1].parent_id, folder);
        manifest.document.modules = { 'unavailable-instrument': { schema_version: 7, state: { identifier: 'NATIVE_INT64' } } };
        const documentJson = JSON.stringify(manifest.document).replace('"NATIVE_INT64"', '9223372036854775807');
        const manifestText = '{"format":"liberu.music.session","format_version":1,"title":"Browser session","document":' + documentJson + ',"checksum":"' + createHash('sha256').update(documentJson).digest('hex') + '"}';
        await writeFile(manifestFile, manifestText);
        await page.getByText('Open a portable session', { exact: true }).click();
        await page.getByLabel('Choose a portable session manifest').setInputFiles(manifestFile);
        await page.getByText('session.music.json', { exact: true }).waitFor();
        await page.getByRole('button', { name: 'Review import', exact: true }).click();
        await page.getByRole('button', { name: 'Confirm import', exact: true }).click();
        await page.getByText('Portable session imported and opened.', { exact: true }).waitFor();
        await page.getByLabel('Session name', { exact: true }).fill('Autosaved browser');
        await page.getByRole('button', { name: 'Save autosave', exact: true }).click();
        await page.getByText('Autosave confirmed by the server.', { exact: true }).waitFor();
        await page.getByRole('button', { name: 'Review revision 1', exact: true }).click();
        await page.getByRole('button', { name: 'Confirm recovery', exact: true }).click();
        await page.getByText('Recovery checkpoint confirmed by the server.', { exact: true }).waitFor();
        await page.getByText(/Based on revision 3/).waitFor();
        await page.getByLabel('Session name', { exact: true }).fill('Offline browser draft');
        await page.getByText('Draft backup and offline recovery', { exact: true }).click();
        await context.setOffline(true);
        await page.getByText(/Connection lost\. Keep this page open/).waitFor();
        const draftDownload = page.waitForEvent('download');
        await page.getByRole('button', { name: 'Download current draft backup', exact: true }).click();
        const draftFile = path.join(output, 'offline.music-draft.json');
        await (await draftDownload).saveAs(draftFile);
        const draft = JSON.parse(await readFile(draftFile, 'utf8'));
        assert.equal(draft.schema_version, 2);
        assert.match(draft.modules_json, /"identifier":9223372036854775807/);
        assert.equal(draft.title, 'Offline browser draft');
        assert.equal(draft.version, 3);
        assert.equal(draft.workspace_id, workspace);
        assert.equal(draft.document.tracks.length, 2);
        await context.setOffline(false);
        await page.reload();
        await page.getByRole('heading', { name: 'Session draft', exact: true }).waitFor();
        await page.getByText('Draft backup and offline recovery', { exact: true }).click();
        await page.getByLabel('Restore a draft backup after reconnecting').setInputFiles(draftFile);
        await page.getByRole('button', { name: 'Restore draft for review', exact: true }).click();
        await page.getByText(/Draft restored without saving or rebasing/).waitFor();
        assert.equal(await page.getByLabel('Session name', { exact: true }).inputValue(), 'Offline browser draft');
        await page.getByRole('button', { name: 'Save checkpoint', exact: true }).focus();
        await page.keyboard.press('Enter');
        await page.getByText(/Based on revision 4/).waitFor();
        const recoveredDownload = page.waitForEvent('download');
        await page.getByRole('button', { name: 'Export saved revision', exact: true }).click();
        const recoveredFile = path.join(output, 'recovered.music.json');
        await (await recoveredDownload).saveAs(recoveredFile);
        assert.match(await readFile(recoveredFile, 'utf8'), /"identifier":9223372036854775807/, 'Opaque native state must survive browser backup and recovery without numeric rounding.');
        await page.screenshot({ path: path.join(output, 'workspace-desktop.png'), fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 });
        await page.screenshot({ path: path.join(output, 'workspace-mobile.png'), fullPage: true });
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'The workspace must fit a narrow viewport without page-level horizontal scrolling.');
        assert.deepEqual(errors, [], 'No uncaught client-side errors should occur.');
        await context.close();
    } catch (error) {
        if (page) {
            await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true });
            const details = await page.locator('details').evaluateAll(items => items.map(item => ({ open: item.open, text: item.textContent })));
            const alerts = await page.locator('[role=alert]').allTextContents();
            throw new Error(error.message + '\nUI diagnostics: ' + JSON.stringify({ details, alerts, errors }), { cause: error });
        }
        throw error;
    } finally {
        await browser.close();
    }
});
